// A model server that accepts connections and never replies (the F-03 hang).
const sockets = new Set();
const hangServer = net.createServer(s => { sockets.add(s); s.on('error', () => {}); s.on('close', () => sockets.delete(s)); });
await new Promise(r => hangServer.listen(0, '127.0.0.1', r));
after(async () => { for (const s of sockets) s.destroy(); await new Promise(r => hangServer.close(r)); });

setTestEnv();
process.env.LLM_API_URL = `http://127.0.0.1:${hangServer.address().port}/v1/chat/completions`;
process.env.OPENSEARCH_URL = 'http://127.0.0.1:9';   // refused at once: no SIEM in these tests
process.env.LLM_PLANNER_TIMEOUT_MS = '300';
process.env.LLM_REPORT_TIMEOUT_MS = '300';
process.env.LLM_MEMORY_TIMEOUT_MS = '300';
process.env.LLM_CONVERSATION_TIMEOUT_MS = '300';
process.env.LLM_DEFAULT_TIMEOUT_MS = '300';

const { initDatabase } = await import('../src/config/db.js');
