const { memoryManager } = await import('../src/memory/manager.js');
const { RunModel } = await import('../src/models/Run.js');
initDatabase();

const quiet = t => { for (const level of ['log', 'warn', 'error']) t.mock.method(console, level, () => {}); };
const fakeRes = () => ({ statusCode: 200, body: undefined, status(c) { this.statusCode = c; return this; }, json(b) { this.body = b; return this; } });

// ---------------------------------------------------------------- F-03: real timeouts, clean fallbacks

test('Search Wazuh with a hung model: planner and report time out, the run falls back and finishes', async (t) => {
    quiet(t);
    // The search succeeds (so the report stage asks the model); every model call goes to the hung server.
    const original = axios.post;
    t.mock.method(axios, 'post', (url, body, config) => (String(url).includes('/_search')
        ? Promise.resolve({ status: 200, data: { hits: { total: { value: 1 }, hits: [{ _source: SAMPLE_LOG }] } } })
        : original.call(axios, url, body, config)));
    const started = Date.now();
    const response = await runAgentWorkflow('show me failed logons today', [], USER_ID);
    assert.ok(Date.now() - started < 4000, `must not wait indefinitely (took ${Date.now() - started} ms)`);

    const run = RunModel.findById(response.request_id);
    assert.equal(run.status, 'completed');
    assert.equal(run.planner.source, 'fallback_rules', 'planner timed out and the rule-based plan was used');
    assert.equal(run.generation.report, 'fallback_model_unavailable');
    assert.match(response.summary, /not generated by a model/);
    assert.ok(run.errors.some(e => e.stage === 'llm' && /timeout|aborted|canceled/i.test(e.message)), JSON.stringify(run.errors));
    await flushBackgroundWork();
});

test('conversation with a hung model: a graceful answer over HTTP 200, never a 503', async (t) => {
    quiet(t);
    const res = fakeRes();
    const started = Date.now();
    await handleChat({ body: { text: 'hello', history: [] }, user: { id: USER_ID } }, res);
    assert.ok(Date.now() - started < 3000);
    assert.equal(res.statusCode, 200);
    assert.equal(res.body.type, 'text');
    assert.equal(res.body.model_generated, false);
    assert.match(res.body.text, /model is unavailable/i);
});

test('every model call carries a real timeout and an abort signal', async (t) => {
    quiet(t);
    const configs = [];
    t.mock.method(axios, 'post', async (url, body, config) => {
        if (body?.messages) {
            configs.push({ system: body.messages[0].content.slice(0, 40), timeout: config?.timeout, signal: config?.signal });
            const sys = body.messages[0].content;
            if (sys.includes('Planning Engine')) return { data: { choices: [{ message: { content: JSON.stringify(SEARCH_PLAN) } }] } };
            if (sys.includes('Memory Engine')) return { data: { choices: [{ message: { content: '{"summary":"s","keyEntities":[]}' } }] } };
            return { data: { choices: [{ message: { content: 'report' } }] } };
        }
        return { data: { hits: { total: { value: 1 }, hits: [{ _source: SAMPLE_LOG }] } } };
    });
    await runAgentWorkflow('show me failed logons today', [], USER_ID);   // planner + report + memory summary
    await processChatQuery('hello', [], USER_ID);                          // conversation
    await flushBackgroundWork();

    assert.ok(configs.length >= 4, `expected planner, report, memory and conversation calls, got ${configs.length}`);
    for (const c of configs) {
        assert.ok(Number.isFinite(c.timeout) && c.timeout > 0, `call "${c.system}…" has no timeout`);
        assert.ok(c.signal instanceof AbortSignal, `call "${c.system}…" has no abort signal`);
    }
});

test('a call that passes no timeout still gets one (the default), never "wait forever"', async (t) => {
    quiet(t);
    const started = Date.now();
    const reply = await askFoundation('hello', 'SYSTEM PROMPT', []);   // no options at all
    assert.equal(reply, null);
    assert.ok(Date.now() - started < 3000, `took ${Date.now() - started} ms`);
});

test('...and that default is a usable deadline: a model answering normally still gets through', async (t) => {
    quiet(t);
    t.mock.method(axios, 'post', async (url, body, config) => {
        await new Promise((resolve, reject) => {
            const timer = setTimeout(resolve, 50);   // a normal, prompt reply
            config?.signal?.addEventListener('abort', () => { clearTimeout(timer); reject(new Error('aborted')); });
        });
        return { data: { choices: [{ message: { content: 'ok' } }] } };
    });
    assert.equal(await askFoundation('hello', 'SYSTEM PROMPT', []), 'ok');
});

