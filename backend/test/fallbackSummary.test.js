import { test } from 'node:test';
import assert from 'node:assert/strict';
import { setTestEnv, stubBackends, flushBackgroundWork, USER_ID, isFirewallScopeQuery } from './helpers.js';

setTestEnv();
const { initDatabase } = await import('../src/config/db.js');
const { runAgentWorkflow } = await import('../src/agent/runtime.js');
initDatabase();

const PLAN = { thought: 't', tools: [{ tool: 'searchSecurityLogs', parameters: { timeRange: 'now-24h', intent: 'alerts', extractedIPs: [], minSeverity: null, cleanedSearchText: '' } }] };
const rec = (id, desc, level, agent, ip) => ({ '@timestamp': '2026-10-12T08:00:00Z', rule: { id, level, description: desc }, agent: { name: agent }, data: { srcip: ip } });
const times = (n, make) => Array.from({ length: n }, make);
const NOW = [
    ...times(6, () => rec('60104', 'Windows audit failure event', 5, 'gbb_portal_02', '10.128.52.36')),
    ...times(3, () => rec('60122', 'Logon Failure - Unknown user or bad password', 5, 'GBB_internal_AD', '197.159.67.181')),
    rec('92001', 'Suspicious PowerShell', 12, 'GBB_internal_AD', '206.245.166.45')
];
const WEEK_AGO = times(20, () => rec('60104', 'Windows audit failure event', 5, 'gbb_portal_02', '10.128.52.36'));
const quiet = t => { for (const level of ['log', 'warn', 'error']) t.mock.method(console, level, () => {}); };

async function ask(t, llm) {
    quiet(t);
    stubBackends(t, { llm, logs: (url, body) => (isFirewallScopeQuery(body) ? [] : NOW), previousLogs: WEEK_AGO });
    const response = await runAgentWorkflow('what is going on with the windows hosts', [], USER_ID);
    await flushBackgroundWork();
    return response;
}

const SUMMARY = [
    /\*\*Summary of the results\*\*/,
    /- \*\*Change:\*\* 50% fewer matches than the same 24 hours one week earlier\./,
    /- \*\*Most frequent rules:\*\* 60104 Windows audit failure event \(6\); 60122 Logon Failure - Unknown user or bad password \(3\); 92001 Suspicious PowerShell \(1\)\./,
    /- \*\*Most active agents:\*\* gbb_portal_02 \(6\); GBB_internal_AD \(4\)\./,
    /- \*\*Top source IPs:\*\* 10\.128\.52\.36 \(6\); 197\.159\.67\.181 \(3\); 206\.245\.166\.45 \(1\)\./,
    /- \*\*Highest severity:\*\* level 12 \(1 match\)\./,
    /- \*\*New this period:\*\* rules 60122, 92001 \(not seen in the same 24 hours one week earlier\)\./
];
const NOT_MOCK = /⚠️|couldn't be verified|Model unavailable:|not generated by a model|None of the model's statements|Below is what/;

test('model unavailable: a results summary, with one quiet line saying AI analysis is not included', async (t) => {
    const response = await ask(t, 'down');
    for (const pattern of SUMMARY) assert.match(response.summary, pattern);
    assert.match(response.summary, /^\*\*Searched:\*\*/, 'opens with what was searched, like every answer');
    assert.ok(response.summary.trimEnd().endsWith('_AI analysis is not included: the analysis model could not be reached. This summary is calculated directly from the search results._'));
    assert.doesNotMatch(response.summary, NOT_MOCK);
    assert.equal(response.model_generated, false);
});

test("the model's answer is not in the required format: the same summary, and the line says it was withheld", async (t) => {
    const response = await ask(t, { plan: PLAN, report: 'Free text that cannot be checked.' });
    for (const pattern of SUMMARY) assert.match(response.summary, pattern);
    assert.ok(response.summary.trimEnd().endsWith("_AI analysis is not included: the model's response could not be verified against the search results and was withheld. This summary is calculated directly from the search results._"));
    assert.doesNotMatch(response.summary, NOT_MOCK);
    assert.doesNotMatch(response.summary, /Free text/);
});

test('none of the statements verified: the same treatment', async (t) => {
    const report = JSON.stringify({ answer: [{ text: 'It came from 91.92.93.94.', cite: [{ kind: 'rule', ref: '60104' }] }] });
    const response = await ask(t, { plan: PLAN, report });
    assert.match(response.summary, /\*\*Summary of the results\*\*/);
    assert.match(response.summary, /was withheld\. This summary is calculated directly from the search results\._$/);
    assert.doesNotMatch(response.summary, /91\.92\.93\.94/);
    assert.doesNotMatch(response.summary, NOT_MOCK);
});

test('not enough evidence: a plain statement, then the summary', async (t) => {
    const response = await ask(t, { plan: PLAN, report: JSON.stringify({ insufficient_evidence: true }) });
    assert.match(response.summary, /\*\*Not enough evidence\*\* in these results to answer the question\.\n\n\*\*Summary of the results\*\*/);
    assert.ok(response.summary.trimEnd().endsWith('_This summary is calculated directly from the search results._'));
    assert.doesNotMatch(response.summary, NOT_MOCK);
});
